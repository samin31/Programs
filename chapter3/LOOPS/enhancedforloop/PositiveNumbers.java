package enhancedforloop;

public class PositiveNumbers {
	
	    public static void main(String[] args) {
	        int[] arr = {-5, 10, -20, 30, 40, -8};

	        for (int num : arr) {
	            if (num > 0) {
	                System.out.println(num);
	            
	        }
	    }
	}
}
